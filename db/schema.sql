-- Bijak AI schema (Neon Postgres) — merged design: the team's Shop / Users / Item /
-- Inventory / Sales / SalesItem / Restocklog tables, plus what the app needs
-- (SKU, unit, cost, location, expiry, AI Advisor chats, stock log).
--
-- Naming: Table_Column, written WITHOUT quotes. Postgres stores unquoted names in
-- lowercase (Item_Name → item_name), so SQL can use either spelling; the Neon
-- console shows lowercase. ("User" is a reserved word, hence Users.)
--
-- IDs are identity columns BY DEFAULT: auto-numbered, but an id can still be given
-- (the app creates a product's id in the browser so it can show it right away).
-- Safe to run more than once (IF NOT EXISTS). Run with: npm run db:setup

-- ---------- Shops & people ----------
CREATE TABLE IF NOT EXISTS Shop (
  Shop_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_Name      text NOT NULL,
  Shop_Type      text,
  Shop_Location  text,
  Shop_Active    boolean NOT NULL DEFAULT true,
  Shop_CreatedAt timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS Users (
  User_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID        bigint NOT NULL REFERENCES Shop (Shop_ID),
  User_Name      text NOT NULL,
  User_Email     text UNIQUE,
  User_Tel       text,                               -- text keeps the leading 0 (012-…)
  User_Role      text NOT NULL DEFAULT 'owner' CHECK (User_Role IN ('owner', 'staff')),
  User_Active    boolean NOT NULL DEFAULT true,
  User_CreatedAt timestamptz NOT NULL DEFAULT now()
);

-- ---------- Lookups (per shop) ----------
CREATE TABLE IF NOT EXISTS Category (
  Category_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID            bigint NOT NULL REFERENCES Shop (Shop_ID),
  Category_Name      text NOT NULL,
  Category_CreatedAt timestamptz NOT NULL DEFAULT now(),
  UNIQUE (Shop_ID, Category_Name)
);

CREATE TABLE IF NOT EXISTS Supplier (
  Supplier_ID          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID              bigint NOT NULL REFERENCES Shop (Shop_ID),
  Supplier_Name        text NOT NULL,
  Supplier_ContactName text,
  Supplier_Tel         text,
  Supplier_CreatedAt   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (Shop_ID, Supplier_Name)
);

-- ---------- Catalog & stock ----------
-- The catalog entry. "Delete" in the app sets Item_Active = false, so sales history stays.
CREATE TABLE IF NOT EXISTS Item (
  Item_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID        bigint NOT NULL REFERENCES Shop (Shop_ID),
  Category_ID    bigint REFERENCES Category (Category_ID),
  Supplier_ID    bigint REFERENCES Supplier (Supplier_ID),   -- usual supplier ("Draft order")
  Item_Name      text NOT NULL,
  Item_SKU       text NOT NULL,
  Item_Unit      text NOT NULL,                              -- kg, pcs, box…
  Item_CostPrice numeric(10, 2) NOT NULL DEFAULT 0 CHECK (Item_CostPrice >= 0),
  Item_UnitPrice numeric(10, 2) CHECK (Item_UnitPrice >= 0), -- selling price; NULL = not sold
  Item_Active    boolean NOT NULL DEFAULT true,
  Item_CreatedAt timestamptz NOT NULL DEFAULT now(),
  Item_UpdatedAt timestamptz NOT NULL DEFAULT now()
);
-- A SKU can be reused once the old item is deactivated.
CREATE UNIQUE INDEX IF NOT EXISTS item_sku_active ON Item (Shop_ID, Item_SKU) WHERE Item_Active;

-- How much of it the shop has.
CREATE TABLE IF NOT EXISTS Inventory (
  Inventory_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID             bigint NOT NULL REFERENCES Shop (Shop_ID),
  Item_ID             bigint NOT NULL REFERENCES Item (Item_ID),
  Inventory_Stock     numeric(10, 2) NOT NULL DEFAULT 0 CHECK (Inventory_Stock >= 0),
  Inventory_Min       numeric(10, 2) NOT NULL DEFAULT 0 CHECK (Inventory_Min >= 0),
  Inventory_Max       numeric(10, 2) CHECK (Inventory_Max >= Inventory_Min), -- optional
  Inventory_Location  text NOT NULL DEFAULT '',
  Inventory_Expiry    date,                                 -- earliest expiry on the shelf
  Inventory_UpdatedAt timestamptz NOT NULL DEFAULT now(),
  UNIQUE (Shop_ID, Item_ID)
);

-- ---------- Sales ----------
-- One row per sale. The app's "Record sale" screen keeps one sale per shop per day with
-- Sales_Source = 'daily_entry'; editing it replaces its SalesItem rows.
CREATE TABLE IF NOT EXISTS Sales (
  Sales_ID            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID             bigint NOT NULL REFERENCES Shop (Shop_ID),
  User_ID             bigint REFERENCES Users (User_ID),
  Sales_Date          date NOT NULL,
  Sales_Source        text NOT NULL DEFAULT 'pos' CHECK (Sales_Source IN ('pos', 'daily_entry')),
  Sales_PaymentMethod text,                                 -- cash, ewallet… (NULL for daily_entry)
  Sales_Total         numeric(10, 2) NOT NULL DEFAULT 0,
  Sales_CreatedAt     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS sales_one_daily_entry ON Sales (Shop_ID, Sales_Date) WHERE Sales_Source = 'daily_entry';
CREATE INDEX IF NOT EXISTS sales_shop_date ON Sales (Shop_ID, Sales_Date);

CREATE TABLE IF NOT EXISTS SalesItem (
  SalesItem_ID        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Sales_ID            bigint NOT NULL REFERENCES Sales (Sales_ID) ON DELETE CASCADE,
  Item_ID             bigint NOT NULL REFERENCES Item (Item_ID),
  SalesItem_Quantity  integer NOT NULL CHECK (SalesItem_Quantity > 0),
  SalesItem_UnitPrice numeric(10, 2) NOT NULL DEFAULT 0,    -- price at the time of sale
  SalesItem_Subtotal  numeric(10, 2) GENERATED ALWAYS AS (SalesItem_Quantity * SalesItem_UnitPrice) STORED,
  UNIQUE (Sales_ID, Item_ID)
);
CREATE INDEX IF NOT EXISTS salesitem_item ON SalesItem (Item_ID);

-- ---------- Stock history ----------
-- Deliveries from suppliers (for a future "receive delivery" screen).
CREATE TABLE IF NOT EXISTS Restocklog (
  Restocklog_ID          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Shop_ID                bigint NOT NULL REFERENCES Shop (Shop_ID),
  Item_ID                bigint NOT NULL REFERENCES Item (Item_ID),
  Supplier_ID            bigint REFERENCES Supplier (Supplier_ID),
  User_ID                bigint REFERENCES Users (User_ID),
  Restocklog_QuantityAdd numeric(10, 2) NOT NULL CHECK (Restocklog_QuantityAdd > 0),
  Restocklog_UnitCost    numeric(10, 2),
  Restocklog_Date        date NOT NULL DEFAULT current_date,
  Restocklog_CreatedAt   timestamptz NOT NULL DEFAULT now()
);

-- Damaged goods, entered with each day's sales (one row per item per day). They are
-- taken out of stock. Created by the team with quoted mixed-case names, so keep the quotes.
CREATE TABLE IF NOT EXISTS "DamageLog" (
  "DamageLog_ID"       integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  shop_id              integer CONSTRAINT "constraint_DamageLog_Shop" REFERENCES Shop (Shop_ID),
  item_id              integer CONSTRAINT "constraint_DamageLog_item" REFERENCES Item (Item_ID),
  user_id              integer CONSTRAINT "constraint_DamageLog_User" REFERENCES Users (User_ID),
  "DamageLog_Quantity" integer NOT NULL,
  "DamageLog_Reason"   varchar,
  "DamageLog_Date"     date NOT NULL
);

-- Every change shown in Inventory → Log (created, edits).
-- Sales are read from SalesItem instead of being logged twice.
-- Text id: made in the browser, so re-sending an entry never duplicates it (upsert).
CREATE TABLE IF NOT EXISTS StockLog (
  StockLog_ID         text PRIMARY KEY,
  Shop_ID             bigint NOT NULL REFERENCES Shop (Shop_ID),
  Item_ID             bigint NOT NULL REFERENCES Item (Item_ID),
  StockLog_Kind       text NOT NULL CHECK (StockLog_Kind IN ('created', 'edit')),
  StockLog_Delta      numeric(10, 2) NOT NULL DEFAULT 0,
  StockLog_StockAfter numeric(10, 2),
  StockLog_Note       text NOT NULL DEFAULT '',
  StockLog_CreatedAt  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stocklog_item ON StockLog (Item_ID, StockLog_CreatedAt);

-- ---------- AI Advisor ----------
-- Chat_Kind 'dashboard': one per day (id 'dashboard-yyyy-mm-dd'); today's is pinned.
-- Chat_Kind 'advice': the pinned "Today's advice" chat. 'chat': normal chats.
-- Text ids: created in the browser so a message shows before the server answers.
CREATE TABLE IF NOT EXISTS Chat (
  Chat_ID        text PRIMARY KEY,
  Shop_ID        bigint NOT NULL REFERENCES Shop (Shop_ID),
  User_ID        bigint REFERENCES Users (User_ID),
  Chat_Kind      text NOT NULL DEFAULT 'chat' CHECK (Chat_Kind IN ('chat', 'dashboard', 'advice')),
  Chat_Day       date,
  Chat_Title     text NOT NULL,
  Chat_CreatedAt timestamptz NOT NULL DEFAULT now(),
  Chat_UpdatedAt timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS chat_one_dashboard_per_day ON Chat (Shop_ID, Chat_Day) WHERE Chat_Kind = 'dashboard';

CREATE TABLE IF NOT EXISTS Message (
  Message_ID        text PRIMARY KEY,
  Chat_ID           text NOT NULL REFERENCES Chat (Chat_ID) ON DELETE CASCADE,
  Message_Role      text NOT NULL CHECK (Message_Role IN ('user', 'ai')),
  Message_Text      text NOT NULL,
  Message_CreatedAt timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS message_chat ON Message (Chat_ID, Message_CreatedAt);

-- Advice cards the owner pressed "Not now" on (ids from src/lib/advice.js).
CREATE TABLE IF NOT EXISTS DismissedAdvice (
  Shop_ID                 bigint NOT NULL REFERENCES Shop (Shop_ID),
  Advice_ID               text NOT NULL,
  DismissedAdvice_At      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (Shop_ID, Advice_ID)
);
